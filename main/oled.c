// Send command byte to OLED
static esp_err_t oled_cmd(uint8_t cmd) {
    i2c_cmd_handle_t handle = i2c_cmd_link_create();
    i2c_master_start(handle);
    i2c_master_write_byte(handle, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(handle, 0x00, true); // Command mode
    i2c_master_write_byte(handle, cmd,  true);
    i2c_master_stop(handle);
    esp_err_t ret = i2c_master_cmd_begin(I2C_PORT, handle, pdMS_TO_TICKS(100));
    i2c_cmd_link_delete(handle);
    return ret;
}

// Send data bytes to OLED
static esp_err_t oled_data(uint8_t *data, size_t len) {
    i2c_cmd_handle_t handle = i2c_cmd_link_create();
    i2c_master_start(handle);
    i2c_master_write_byte(handle, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(handle, 0x40, true); // Data mode
    i2c_master_write(handle, data, len, true);
    i2c_master_stop(handle);
    esp_err_t ret = i2c_master_cmd_begin(I2C_PORT, handle, pdMS_TO_TICKS(100));
    i2c_cmd_link_delete(handle);
    return ret;
}

// Initialize OLED display
esp_err_t oled_init(void) {
    uint8_t init_cmds[] = {
        0xAE,       // Display OFF
        0xD5, 0x80, // Clock divide ratio
        0xA8, 0x3F, // Multiplex ratio (64 lines)
        0xD3, 0x00, // Display offset = 0
        0x40,       // Start line = 0
        0x8D, 0x14, // Enable charge pump
        0x20, 0x00, // Horizontal addressing mode
        0xA1,       // Segment remap (flip horizontal)
        0xC8,       // COM scan direction (flip vertical)
        0xDA, 0x12, // COM pins hardware config
        0x81, 0xCF, // Contrast = 207
        0xD9, 0xF1, // Pre-charge period
        0xDB, 0x40, // VCOMH deselect level
        0xA4,       // Entire display ON (from RAM)
        0xA6,       // Normal display (not inverted)
        0xAF,       // Display ON
    };

    for(int i = 0; i < sizeof(init_cmds); i++) {
        if(oled_cmd(init_cmds[i]) != ESP_OK) {
            ESP_LOGE(TAG, "OLED init failed at cmd 0x%02X", init_cmds[i]);
            return ESP_FAIL;
        }
    }

    ESP_LOGI(TAG, "OLED initialized successfully!");
    return oled_clear();
}

// Clear entire display
esp_err_t oled_clear(void) {
    for(uint8_t page = 0; page < 8; page++) {
        oled_cmd(0xB0 + page);
        oled_cmd(0x00);
        oled_cmd(0x10);
        uint8_t zeros[128] = {0};
        oled_data(zeros, 128);
    }
    return ESP_OK;
}

// Print text at a given row (0-7)
esp_err_t oled_print(uint8_t row, const char *text) {
    oled_cmd(0xB0 + row);
    oled_cmd(0x00);
    oled_cmd(0x10);

    for(int i = 0; text[i] != '\0' && i < 21; i++) {
        uint8_t c = (uint8_t)text[i];
        if(c < 32 || c > 'z') c = 32;
        uint8_t glyph[6];
        memcpy(glyph, font5x7[c - 32], 5);
        glyph[5] = 0x00;
        oled_data(glyph, 6);
    }
    return ESP_OK;
}